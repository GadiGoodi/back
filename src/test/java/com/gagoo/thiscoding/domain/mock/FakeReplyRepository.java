package com.gagoo.thiscoding.domain.mock;

import com.gagoo.thiscoding.domain.maria.reply.domain.Reply;
import com.gagoo.thiscoding.domain.maria.reply.service.dto.ReplyList;
import com.gagoo.thiscoding.domain.maria.reply.service.port.ReplyRepository;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.support.PageableExecutionUtils;

import java.time.LocalDateTime;
import java.util.*;
import java.util.stream.Collectors;

public class FakeReplyRepository implements ReplyRepository {

    private Long autoGeneratedId = 0L;
    private final List<Reply> data = new ArrayList<>();

    @Override
    public Reply save(Reply reply) {
        if (reply.getId() == null || reply.getId() == 0) {
            Reply savedReply = Reply.builder()
                    .id(++autoGeneratedId)
                    .qnaId(reply.getQnaId())
                    .user(reply.getUser())
                    .content(reply.getContent())
                    .parent(reply.getParent() != null ? findById(reply.getParent().getId()).orElse(null) : null)
                    .isBlinded(reply.isBlinded())
                    .createDate(LocalDateTime.now())
                    .build();
            data.add(savedReply);

            return savedReply;
        } else {
            data.removeIf(item -> item.getId().equals(reply.getId()));
            data.add(reply);

            return reply;
        }
    }

    @Override
    public Optional<Reply> findById(Long id) {
        return data.stream()
                .filter(item -> item.getId().equals(id))
                .findAny();
    }

    @Override
    public Page<ReplyList> findByQnaId(String qnaId, Pageable pageable) {
        if (pageable.getPageSize() < 1) {
            return Page.empty(pageable);
        }

        List<ReplyList> findAllReply = data.stream()
                .filter(reply -> reply.getQnaId().equals(qnaId))
                .sorted(Comparator.comparing(Reply::getCreateDate).reversed())
                .map(reply -> ReplyList.builder()
                        .replyId(reply.getId())
                        .parentId(reply.getParent() != null ? reply.getParent().getId() : null)
                        .nickname(reply.getUser().getNickname())
                        .profileImage(reply.getUser().getImageUrl())
                        .content(reply.getContent())
                        .createDate(reply.getCreateDate())
                        .build())
                .collect(Collectors.toList());

        int start = (int) pageable.getOffset();
        int end = Math.min(start + pageable.getPageSize(), findAllReply.size());

        if (start >= findAllReply.size()) {
            return Page.empty(pageable);
        }

        List<ReplyList> pagedReplies = findAllReply.subList(start, end);

        return PageableExecutionUtils.getPage(
                pagedReplies,
                pageable,
                () -> (long) findAllReply.size()
        );
    }

    @Override
    public Long countByQnaId(String qnaId) {
        return data.stream().filter(item -> item.getQnaId().equals(qnaId)).count();
    }

    @Override
    public boolean existsById(Long parentId) {
        return data.stream()
                .anyMatch(reply -> reply.getParent() != null &&
                        reply.getParent().getId() != null &&
                        reply.getParent().getId().equals(parentId));
    }

    @Override
    public void delete(Reply reply) {

    }

    @Override
    public Page<ReplyList> findRepliesByParentId(String qnaId, Long parentId, Pageable pageable) {
        List<ReplyList> replies = data.stream()
                .filter(reply -> reply.getQnaId().equals(qnaId) &&
                        reply.getParent() != null &&
                        reply.getParent().getId().equals(parentId))
                .sorted(Comparator.comparing(Reply::getCreateDate).reversed())
                .map(reply -> ReplyList.builder()
                        .replyId(reply.getId())
                        .parentId(reply.getParent().getId())
                        .nickname(reply.getUser().getNickname())
                        .profileImage(reply.getUser().getImageUrl())
                        .content(reply.getContent())
                        .createDate(reply.getCreateDate())
                        .build())
                .toList();

        int start = (int) pageable.getOffset();
        int end = Math.min(start + pageable.getPageSize(), replies.size());

        if (start >= replies.size()) {
            return Page.empty(pageable);
        }

        List<ReplyList> pagedReplies = replies.subList(start, end);

        return PageableExecutionUtils.getPage(
                pagedReplies,
                pageable,
                () -> (long) replies.size()
        );
    }
}
